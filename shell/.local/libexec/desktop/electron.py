#!/usr/bin/env python3
"""Chromium flags for Electron apps, through their desktop entries.

Fedora launchers of Electron apps read no flags file, so for every desktop ID in
~/.config/desktop/electron-apps.conf this writes ~/.local/share/applications/<id>.desktop: the entry of the
app with the flags of ~/.config/electron-flags.conf after the program on every Exec line. The copy takes
precedence over the system one and keeps its ID. An entry that exists only in the user directory (made by
hand) is updated in place. A user entry that is a link (a Stow package of the dotfiles) is left alone: it
carries its flags itself. Flags these files used to carry for the same purpose are replaced, not doubled.

apply: write the entries (run by desktop-session at login, so package updates are followed).
status: print, per app, the source entry, whether the generated one is current and whether it is a link.
"""
from common import write_atomic
from i18n import tr
import json
import os
from pathlib import Path
import re
import shlex
import sys

HOME = Path.home()
CONFIG = Path(os.environ.get('XDG_CONFIG_HOME') or HOME / '.config')
DATA = Path(os.environ.get('XDG_DATA_HOME') or HOME / '.local/share')
FLAGS = CONFIG / 'electron-flags.conf'
APPS = CONFIG / 'desktop/electron-apps.conf'
TARGET = DATA / 'applications'
MARKER = '# Generated by ~/.local/libexec/desktop/electron.py from '
# Older spellings of the same switches, dropped before the configured ones are added.
REPLACED = ('--ozone-platform', '--ozone-platform-hint', '--enable-wayland-ime', '--wayland-text-input-version',
            '--enable-features=UseOzonePlatform')


def lines(path):
    try:
        text = path.read_text(encoding='utf-8')
    except OSError:
        return []
    return [line.strip() for line in text.splitlines() if line.strip() and not line.strip().startswith('#')]


def flags():
    return [flag for line in lines(FLAGS) for flag in shlex.split(line)]


def replaced(argument, configured):
    name = argument.split('=', 1)[0]
    return argument in configured or argument in REPLACED or name in {flag.split('=', 1)[0] for flag in configured} \
        or name in REPLACED


# Desktop entries quote with double quotes only (the shell's single quotes are not part of the format).
def quote(word):
    if re.fullmatch(r'[\w@%+=:,./-]+', word):
        return word
    return '"' + re.sub(r'(["`$\\])', r'\\\1', word) + '"'


# Exec=[env VAR=value ...] program [args] -> the flags right after the program, older ones dropped from the
# arguments. Field codes (%U, %F) stay where they were.
def with_flags(exec_line, configured):
    words = shlex.split(exec_line)
    start = 0
    if words and words[0] == 'env':
        start = 1
        while start < len(words) and '=' in words[start] and not words[start].startswith('-'):
            start += 1
    if start >= len(words):
        return exec_line
    rest = [word for word in words[start + 1:] if not replaced(word, configured)]
    return ' '.join(quote(word) for word in words[:start + 1] + configured + rest)


def rewrite(text, configured, source):
    out = [MARKER + str(source)]
    for line in text.splitlines():
        if line.startswith(MARKER):
            continue
        if line.startswith('Exec='):
            line = 'Exec=' + with_flags(line[len('Exec='):], configured)
        out.append(line)
    return '\n'.join(out) + '\n'


# Flatpak exports are left out: their Exec runs flatpak, and the flags would need to go after the app ID.
def data_dirs():
    return [Path(path) for path in (os.environ.get('XDG_DATA_DIRS') or '/usr/local/share:/usr/share').split(':')
            if path and 'flatpak' not in path]


# The system entry when there is one; else a user entry made by hand (updated in place).
def source_for(app_id):
    for directory in data_dirs():
        path = directory / 'applications' / (app_id + '.desktop')
        if path.is_file():
            return path
    own = TARGET / (app_id + '.desktop')
    return own if own.is_file() else None


def plan():
    configured = flags()
    result = []
    for app_id in lines(APPS):
        source = source_for(app_id)
        target = TARGET / (app_id + '.desktop')
        if target.is_symlink():
            result.append({'app': app_id, 'source': str(target), 'current': False, 'linked': True})
            continue
        if source is None:
            result.append({'app': app_id, 'source': None, 'current': False})
            continue
        text = rewrite(source.read_text(encoding='utf-8'), configured, source)
        try:
            current = target.read_text(encoding='utf-8') == text
        except OSError:
            current = False
        result.append({'app': app_id, 'source': str(source), 'target': target, 'text': text, 'current': current})
    return result


def main():
    arguments = sys.argv[1:]
    if arguments == ['apply']:
        for entry in plan():
            if 'text' in entry and not entry['current']:
                write_atomic(entry['target'], entry['text'])
    elif arguments == ['status']:
        print(json.dumps([{key: value for key, value in entry.items() if key in ('app', 'source', 'current', 'linked')}
                          for entry in plan()], indent=2))
    else:
        print(tr('electron.errors.usage'), file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
