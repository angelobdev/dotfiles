#!/usr/bin/env python3
"""Hyprland settings chosen in Settings, rendered into ~/.config/desktop/settings.lua.

The choices live under "hyprland" in ~/.config/desktop/shell.json (Settings writes them there, Config.qml):
{"keyboard": {"layout": "it", "variant": ""}, "assistantLanguage": "italian",
 "binds": [{"keys": "SUPER + B", "command": "zen-browser", "description": "Browser"}]}.
hyprland.lua loads settings.lua after its own modules and before the user's hypr.lua, which still wins.

render [--json TEXT]: writes settings.lua from TEXT (or from shell.json), or removes it when nothing is set, and
reloads Hyprland when it changed (a new or removed file is not one Hyprland watches); prints
{"changed": bool, "skipped": [what was not valid]}.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

from common import write_atomic

CONFIG = Path(os.environ.get('XDG_CONFIG_HOME') or Path.home() / '.config') / 'desktop'
LAYOUT = re.compile(r'^[a-z]{2,8}(,[a-z]{2,8})*$')
VARIANT = re.compile(r'^[a-z0-9_-]*(,[a-z0-9_-]*)*$')
LANGUAGE = re.compile(r'^[a-z]{2,20}$')
# Modifiers and one key, as Hyprland binds take them: "SUPER + SHIFT + B", "SUPER + period", "XF86AudioMute".
MODIFIERS = {'SUPER', 'SHIFT', 'CTRL', 'CONTROL', 'ALT', 'MOD2', 'MOD3', 'MOD5'}
KEY = re.compile(r'^[A-Za-z0-9_]+$')
HEADER = """-- Generated by Settings (hyprsettings.py) from "hyprland" in shell.json: changes here are overwritten.
-- Your own Hyprland settings go in hypr.lua, loaded after this file, so they win.
"""


def lua_string(value):
    # A double-quoted Lua string: backslash, quote and control characters escaped.
    text = str(value).replace('\\', '\\\\').replace('"', '\\"')
    return '"' + re.sub(r'[\x00-\x1f\x7f]', lambda match: f'\\{ord(match[0]):03d}', text) + '"'


def valid_keys(keys):
    parts = [part.strip() for part in str(keys).split('+')]
    if not parts or any(part == '' for part in parts):
        return None
    *modifiers, key = parts
    if any(part.upper() not in MODIFIERS for part in modifiers) or not KEY.match(key):
        return None
    return ' + '.join([part.upper() for part in modifiers] + [key])


def render(settings):
    """The text of settings.lua, '' when nothing is set, and what was left out as not valid."""
    lines, skipped = [], []
    if not isinstance(settings, dict):
        return '', ['hyprland'] if settings not in (None, {}) else []
    keyboard = settings.get('keyboard') if isinstance(settings.get('keyboard'), dict) else {}
    layout = str(keyboard.get('layout') or '').strip()
    variant = str(keyboard.get('variant') or '').strip()
    if layout:
        if LAYOUT.match(layout) and VARIANT.match(variant):
            lines.append(f'hl.config({{ input = {{ kb_layout = {lua_string(layout)}, kb_variant = {lua_string(variant)} }} }})')
        else:
            skipped.append('keyboard')
    language = str(settings.get('assistantLanguage') or '').strip()
    if language:
        if LANGUAGE.match(language):
            lines.append(f'hl.env("DESKTOP_AI_LANGUAGE", {lua_string(language)})')
        else:
            skipped.append('assistantLanguage')
    binds = settings.get('binds') if isinstance(settings.get('binds'), list) else []
    for index, bind in enumerate(binds):
        if not isinstance(bind, dict):
            skipped.append(f'binds.{index}')
            continue
        keys = valid_keys(bind.get('keys', ''))
        command = str(bind.get('command') or '').strip()
        if not keys or not command:
            skipped.append(f'binds.{index}')
            continue
        description = str(bind.get('description') or '').strip() or command
        lines.append(f'hl.bind({lua_string(keys)}, hl.dsp.exec_cmd({lua_string(command)}), {{ description = {lua_string(description)} }})')
    return (HEADER + '\n'.join(lines) + '\n') if lines else '', skipped


def from_shell_json(path=None):
    path = path or CONFIG / 'shell.json'
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return {}
    return data.get('hyprland', {}) if isinstance(data, dict) else {}


def write(text, target=None):
    target = target or CONFIG / 'settings.lua'
    try:
        current = target.read_text(encoding='utf-8')
    except OSError:
        current = None
    if text == '':
        if current is None:
            return False
        target.unlink()
        return True
    if current == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    write_atomic(target, text)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    rendering = commands.add_parser('render')
    rendering.add_argument('--json')
    arguments = parser.parse_args()
    settings = from_shell_json() if arguments.json is None else json.loads(arguments.json)
    text, skipped = render(settings)
    changed = write(text)
    if changed and os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        subprocess.run(['hyprctl', 'reload'], capture_output=True, check=False, timeout=10)
    print(json.dumps({'changed': changed, 'skipped': skipped}))


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
