#!/usr/bin/env python3
"""hyprsettings.py: the Hyprland settings of Settings rendered into settings.lua, and nothing unsafe through."""
from pathlib import Path
import sys
import tempfile
import unittest

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'shell/.local/libexec/desktop'))
import hyprsettings  # noqa: E402


class RenderTests(unittest.TestCase):
    def test_nothing_set_renders_nothing(self):
        for settings in ({}, None, {'keyboard': {'layout': ''}, 'binds': []}):
            self.assertEqual(hyprsettings.render(settings), ('', []))

    def test_layout_language_and_binds(self):
        text, skipped = hyprsettings.render({
            'keyboard': {'layout': 'us,it', 'variant': 'intl,'},
            'assistantLanguage': 'italian',
            'binds': [{'keys': 'super + shift + b', 'command': 'zen-browser', 'description': 'Browser'},
                      {'keys': 'SUPER + period', 'command': 'kitty'}]})
        self.assertEqual(skipped, [])
        self.assertTrue(text.startswith('-- Generated by Settings'))
        self.assertIn('hl.config({ input = { kb_layout = "us,it", kb_variant = "intl," } })', text)
        self.assertIn('hl.env("DESKTOP_AI_LANGUAGE", "italian")', text)
        self.assertIn('hl.bind("SUPER + SHIFT + b", hl.dsp.exec_cmd("zen-browser"), { description = "Browser" })', text)
        # No description: the command stands for it.
        self.assertIn('hl.bind("SUPER + period", hl.dsp.exec_cmd("kitty"), { description = "kitty" })', text)

    def test_strings_cannot_break_out_of_lua(self):
        text, _ = hyprsettings.render({'binds': [{'keys': 'SUPER + T', 'command': 'notify-send "hi" \\ end\n)--', 'description': 'a"b'}]})
        self.assertIn(r'hl.dsp.exec_cmd("notify-send \"hi\" \\ end\010)--")', text)
        self.assertIn(r'{ description = "a\"b" }', text)
        self.assertEqual(text.count('\n'), 3)

    @unittest.skipUnless(__import__('shutil').which('lua'), 'lua not installed')
    def test_the_lua_runs_and_says_what_it_should(self):
        import subprocess
        text, _ = hyprsettings.render({'keyboard': {'layout': 'de', 'variant': 'nodeadkeys'}, 'assistantLanguage': 'german',
                                       'binds': [{'keys': 'SUPER + T', 'command': 'notify-send "hi" \\ end\n)--', 'description': 'a"b'}]})
        stub = (
            'local out = {}\n'
            'hl = { config = function(t) out[#out + 1] = "kb=" .. t.input.kb_layout .. "/" .. t.input.kb_variant end,\n'
            '       env = function(k, v) out[#out + 1] = k .. "=" .. v end,\n'
            '       bind = function(k, d, f) out[#out + 1] = k .. "|" .. d .. "|" .. f.description end,\n'
            '       dsp = { exec_cmd = function(c) return c end } }\n')
        result = subprocess.run(['lua', '-'], input=stub + text + '\nprint(table.concat(out, "\\n"))', capture_output=True, text=True, check=True)
        self.assertEqual(result.stdout.splitlines(), ['kb=de/nodeadkeys', 'DESKTOP_AI_LANGUAGE=german', 'SUPER + T|notify-send "hi" \\ end', ')--|a"b'])

    def test_what_is_not_valid_is_left_out_and_named(self):
        text, skipped = hyprsettings.render({
            'keyboard': {'layout': 'it"); os.exit()', 'variant': ''},
            'assistantLanguage': 'Italian!',
            'binds': [{'keys': 'HYPER + B', 'command': 'x'}, {'keys': 'SUPER +', 'command': 'x'}, {'keys': 'SUPER + B', 'command': ''}, 'nonsense']})
        self.assertEqual(text, '')
        self.assertEqual(skipped, ['keyboard', 'assistantLanguage', 'binds.0', 'binds.1', 'binds.2', 'binds.3'])

    def test_monitors_go_through_displays_with_listed_modes_only(self):
        available = {'DP-1': ['1920x1080@60.00', '1280x720@60.00'], 'eDP-1': ['2880x1800@120.00']}
        text, skipped = hyprsettings.render({'monitors': {
            'DP-1': {'mode': '1920x1080@60.00', 'position': 'auto-right', 'scale': 1.25},
            'eDP-1': {'scale': 1.6667, 'position': 'auto'},
            'HDMI-A-1': {'mode': '3840x2160@60.00'}}}, available)
        self.assertEqual(skipped, [])
        self.assertIn('local displays = require("config.displays")', text)
        self.assertIn('displays.configure("DP-1", { mode = "1920x1080@60.00", position = "auto-right", scale = "1.25" })', text)
        self.assertIn('displays.configure("eDP-1", { position = "auto", scale = "1.667" })', text)
        # Not connected now: its mode cannot be checked, and stays as chosen when it was.
        self.assertIn('displays.configure("HDMI-A-1", { mode = "3840x2160@60.00" })', text)

    def test_a_mode_the_monitor_does_not_report_is_refused(self):
        available = {'DP-1': ['1920x1080@60.00']}
        for fields in ({'mode': '1920x1080@75.00'}, {'mode': '1920x1080@60.00@x'}, {'position': '100x0'}, {'scale': 7},
                       {'scale': True}, {'scale': '2'}, {}, 'nonsense'):
            text, skipped = hyprsettings.render({'monitors': {'DP-1': fields}}, available)
            self.assertEqual((text, skipped), ('', ['monitors.DP-1']), fields)
        self.assertEqual(hyprsettings.render({'monitors': {'DP 1; os.exit()': {'scale': 1}}}, {})[1], ['monitors.DP 1; os.exit()'])

    def test_write_only_on_change_and_remove_when_empty(self):
        with tempfile.TemporaryDirectory() as folder:
            target = Path(folder) / 'desktop/settings.lua'
            self.assertFalse(hyprsettings.write('', target))
            self.assertTrue(hyprsettings.write('a\n', target))
            self.assertFalse(hyprsettings.write('a\n', target))
            self.assertTrue(hyprsettings.write('b\n', target))
            self.assertEqual(target.read_text(), 'b\n')
            self.assertTrue(hyprsettings.write('', target))
            self.assertFalse(target.exists())

    def test_settings_come_from_shell_json(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / 'shell.json'
            path.write_text('{"dockIconSize": 48, "hyprland": {"assistantLanguage": "english"}}')
            self.assertEqual(hyprsettings.from_shell_json(path), {'assistantLanguage': 'english'})
            path.write_text('{ broken')
            self.assertEqual(hyprsettings.from_shell_json(path), {})


if __name__ == '__main__':
    unittest.main()
